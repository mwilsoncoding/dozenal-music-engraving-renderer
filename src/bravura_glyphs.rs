pub(super) fn flag_contours(count: u8, stems_up: bool, levels: &[u8]) -> String {
    let path = flag(count, stems_up).path;
    let contour_starts = path
        .match_indices('M')
        .map(|(index, _)| index)
        .collect::<Vec<_>>();
    let mut result = String::new();
    for level in levels {
        let Some(start) = contour_starts.get(usize::from(*level - 1)) else {
            continue;
        };
        let end = contour_starts
            .get(usize::from(*level))
            .copied()
            .unwrap_or(path.len());
        result.push_str(&path[*start..end]);
    }
    result
}
